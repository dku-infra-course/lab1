#!/usr/bin/env bash
# week01 · 실습 명령 모음
#
# 이 파일은 "복사해서 쓰는 원본"이다. 그대로 실행하는 스크립트가 아니다.
# 실습 문서(실습_W1_환경준비)를 따라가면서 필요한 블록만 복사해서 쓴다.
#
# 아래 값은 본인 환경 값으로 바꾼다.
PUBLIC_IP="10.0.1.29"      # 가상 라우터의 공용 IP (콘솔 Network > Public IP addresses)
VM_IP="192.168.0.10"       # web01 사설 IP
SSH_PORT="2201"            # 포트포워딩으로 연 공용 포트

# ============================================================
# Part 0 · 내 노트북에서 실행
# ============================================================

# 1단계. 도구와 VPN 확인
ssh -V
nc -h 2>&1 | head -3
ifconfig | grep "inet "                  # macOS
# ip -4 addr show                        # Linux
# ipconfig                               # Windows

# 2단계. 콘솔 도달 확인 (301 이 정상. /client/ 로 리다이렉트된다)
curl -I https://dku.kloud.zone

# ============================================================
# Part B~C · 규칙을 만들기 전과 후를 비교한다
# ============================================================

# 6단계. 아직 포트를 열지 않은 상태 (실패가 정상)
nc -vz "$PUBLIC_IP" "$SSH_PORT"

# 9단계. 포트포워딩 + 방화벽을 만든 뒤 (성공해야 한다)
nc -vz "$PUBLIC_IP" "$SSH_PORT"

# ============================================================
# Part D · SSH 접속과 VM 안 점검
# ============================================================

# 10단계. 접속 (계정 ubuntu / 비밀번호 ubuntu)
ssh -p "$SSH_PORT" "ubuntu@$PUBLIC_IP"

# --- 아래는 VM 안에서 실행한다 ---

# 11단계. 내 위치 확인
hostname
ip -4 addr show ens3
ip route
# 기대: default via 192.168.0.1 dev ens3

# 12단계. 아웃바운드 실증 (Egress 규칙이 실제로 동작하는지)
getent hosts ubuntu.com          # DNS  (UDP 53)
curl -I https://ubuntu.com       # HTTPS (TCP 443)
sudo apt update                  # HTTP/HTTPS (TCP 80/443)
ping -c 3 8.8.8.8                # ICMP

# ============================================================
# Part E (선택) · 두 번째 VM 과 사설망 통신
# ============================================================

# 14단계. web01 에서 web02 로
ping -c 3 192.168.0.11
ip neigh

